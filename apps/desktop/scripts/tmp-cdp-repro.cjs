const { chromium } = require('playwright')
async function main() {
  const browser = await chromium.connectOverCDP('http://localhost:9444')
  const contexts = browser.contexts()
  const page = contexts[0].pages().find(p => p.url().includes('index.html'))
  await page.waitForTimeout(500)
  const textarea = page.getByRole('textbox', { name: 'Message' })
  await textarea.click()
  await textarea.type('oi', { delay: 80 })
  await page.waitForTimeout(300)
  const beforeSend = await textarea.inputValue()
  console.log('TEXTAREA_VALUE_JSON', JSON.stringify(beforeSend))
  await page.keyboard.press('Enter')
  await page.waitForTimeout(800)
  const bubbles = await page.locator('[data-slot=bubble-content]').allTextContents()
  console.log('BUBBLES_JSON', JSON.stringify(bubbles))
  const bubbleHtml = await page.locator('[data-slot=bubble-content]').last().innerHTML()
  console.log('LAST_BUBBLE_HTML', bubbleHtml)
  await browser.close()
}
main().catch(e => { console.error('ERR', e); process.exitCode = 1 })
