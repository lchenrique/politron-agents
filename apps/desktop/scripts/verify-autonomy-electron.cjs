// Smoke da interface compilada, sempre em um perfil descartável.
const { _electron } = require('playwright')
const assert = require('node:assert/strict')
const { mkdtempSync, writeFileSync } = require('node:fs')
const { tmpdir } = require('node:os')
const path = require('node:path')
const cwd = path.resolve(__dirname, '..')
const root = mkdtempSync(path.join(tmpdir(), 'boobot-autonomy-ui-'))
const env = { ...process.env, BOOBOT_E2E_USER_DATA_DIR: path.join(root, 'profile') }
delete env.ELECTRON_RUN_AS_NODE
delete env.ELECTRON_RENDERER_URL
let app
async function main() {
  app = await _electron.launch({ executablePath: process.env.BOOBOT_SMOKE_EXECUTABLE || require('electron'), args: process.env.BOOBOT_SMOKE_EXECUTABLE ? [] : [path.join(cwd, 'out/main/index.js')], cwd, env, timeout: 60000 })
  const page = await app.firstWindow()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.waitForFunction(() => !!window.appAPI)
  assert.equal((await page.evaluate(() => window.appAPI.settingsPreferences())).canWrite, true)
  await page.getByRole('button', { name: 'Configurações', exact: true }).click()
  await page.getByRole('button', { name: 'Assistente', exact: true }).click()
  const writing = page.getByRole('checkbox', { name: 'Permitir edição de arquivos do workspace' })
  await writing.waitFor()
  assert.equal(await writing.isChecked(), true)
  await writing.click()
  await page.waitForFunction(async () => (await window.appAPI.settingsPreferences()).canWrite === false)
  await writing.click()
  await page.waitForFunction(async () => (await window.appAPI.settingsPreferences()).canWrite === true)
  await page.getByRole('combobox', { name: 'Aprovações para arquivos e navegador' }).click()
  await page.getByRole('option', { name: 'Bypass · autonomia total' }).click()
  await page.waitForFunction(async () => (await window.appAPI.settingsPreferences()).approvalMode === 'bypass')
  await page.screenshot({ path: path.join(root, 'assistant-access.png') })
  await page.keyboard.press('Escape')
  const chief = await page.evaluate(() => window.appAPI.saveAgent({ name: 'Atlas Smoke UI', role: 'chief', instructions: 'Fixture da interface; não executar tarefas.', canWrite: false, approvalMode: 'ask' }))
  await page.getByRole('button', { name: 'Ações de Atlas Smoke UI' }).click()
  await page.getByRole('menuitem', { name: 'Editar perfil' }).click()
  await page.getByRole('tab', { name: 'Modelo e permissões' }).click()
  const agentWriting = page.getByRole('checkbox', { name: 'Permitir edição de arquivos do workspace' })
  assert.equal(await agentWriting.isChecked(), false)
  await agentWriting.click()
  await page.getByRole('combobox', { name: 'Aprovações para arquivos e navegador' }).click()
  await page.getByRole('option', { name: 'Bypass · autonomia total' }).click()
  await page.screenshot({ path: path.join(root, 'chief-access.png') })
  await page.getByRole('button', { name: 'Salvar alterações' }).click()
  await page.waitForFunction(async id => (await window.appAPI.snapshot()).agents.find(agent => agent.id === id)?.approvalMode === 'bypass', chief.id)
  const saved = await page.evaluate(async id => (await window.appAPI.snapshot()).agents.find(agent => agent.id === id), chief.id)
  assert.equal(saved.canWrite, true)
  assert.deepEqual(errors, [])
  const evidence = { pass: true, assistantWriting: true, chiefWriting: saved.canWrite, chiefApprovalMode: saved.approvalMode, errors, root }
  writeFileSync(path.join(root, 'evidence.json'), JSON.stringify(evidence, null, 2))
  console.log('AUTONOMY_UI_OK', JSON.stringify(evidence))
}
main().catch(error => { console.error('AUTONOMY_UI_FAIL', root, error.stack); process.exitCode = 1 })
  .finally(async () => { if (app) await app.close().catch(() => {}) })
